export const pad = n => String(n).padStart(2, '0');
export const MON_S = ['janv.','févr.','mars','avr.','mai','juin','juil.','août','sept.','oct.','nov.','déc.'];
export const MON_L = ['janvier','février','mars','avril','mai','juin','juillet','août','septembre','octobre','novembre','décembre'];
export const DOW_L = ['Lundi','Mardi','Mercredi','Jeudi','Vendredi','Samedi','Dimanche'];
export const DOW_3 = ['Lun','Mar','Mer','Jeu','Ven','Sam','Dim'];
export const DOW_1 = ['L','M','M','J','V','S','D'];
export const keyOf = d => d.getFullYear() + '-' + pad(d.getMonth() + 1) + '-' + pad(d.getDate());
export const todayKey = () => keyOf(new Date());
export const utc = k => Date.UTC(+k.slice(0, 4), +k.slice(5, 7) - 1, +k.slice(8, 10));
export const fromUtc = t => new Date(t).toISOString().slice(0, 10);
export const addDays = (k, n) => fromUtc(utc(k) + n * 864e5);
export const diffDays = (a, b) => Math.round((utc(b) - utc(a)) / 864e5);
export const dow = k => (new Date(utc(k)).getUTCDay() + 6) % 7;
export const dom = k => +k.slice(8, 10);
export const mon = k => +k.slice(5, 7) - 1;
export const fmtDay = k => (dom(k) === 1 ? '1er' : dom(k)) + ' ' + MON_S[mon(k)];
export const fmtLong = k => DOW_L[dow(k)] + ' ' + (dom(k) === 1 ? '1er' : dom(k)) + ' ' + MON_L[mon(k)];
export const fmtShort = k => DOW_3[dow(k)] + ' ' + fmtDay(k);
export const fmtRange = (a, b) => a === b ? fmtDay(a) : (mon(a) === mon(b) ? (dom(a) === 1 ? '1er' : dom(a)) + '–' + fmtDay(b) : fmtDay(a) + ' – ' + fmtDay(b));
export const mondayOf = k => addDays(k, -dow(k));
export const rangeKeys = (a, b) => { const out = []; for (let k = a; k <= b; k = addDays(k, 1)) out.push(k); return out; };
export const fmtNum = n => String(n).replace('.', ',');
export const r05 = x => Math.round(x * 2) / 2;
export const mmss = s => { s = Math.max(0, Math.round(s)); const m = Math.floor(s / 60); return m + ':' + pad(s % 60); };
